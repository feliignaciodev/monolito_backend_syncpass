-- Proyectos de vinculacion comunitaria
CREATE TABLE proyecto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    descripcion VARCHAR(1000),
    area_tematica VARCHAR(60) NOT NULL,
    unidad_vecinal VARCHAR(100) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_termino DATE NOT NULL,
    estado VARCHAR(20) NOT NULL
);

-- Eventos o talleres; fecha_hora en milisegundos epoch UTC
CREATE TABLE evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proyecto BIGINT NOT NULL REFERENCES proyecto (id),
    nombre VARCHAR(150) NOT NULL,
    fecha_hora BIGINT NOT NULL,
    cupos_maximos INTEGER NOT NULL,
    quorum_minimo INTEGER NOT NULL,
    recinto VARCHAR(150) NOT NULL,
    direccion VARCHAR(200) NOT NULL,
    latitud DOUBLE PRECISION NOT NULL,
    longitud DOUBLE PRECISION NOT NULL,
    radio_metros INTEGER NOT NULL
);
CREATE INDEX ix_evento_proyecto ON evento (id_proyecto);

-- Participantes con identificador sintetico: P-0001 (inscrito previo) o W-<8 hex> (inscrito en sitio)
CREATE TABLE participante (
    id VARCHAR(40) PRIMARY KEY,
    alias VARCHAR(100) NOT NULL,
    tipo VARCHAR(20) NOT NULL
);

CREATE TABLE inscripcion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evento BIGINT NOT NULL REFERENCES evento (id),
    id_participante VARCHAR(40) NOT NULL REFERENCES participante (id),
    estado VARCHAR(20) NOT NULL,
    CONSTRAINT uk_inscripcion_evento_participante UNIQUE (id_evento, id_participante)
);

-- Marcas de asistencia sincronizadas desde los telefonos; uuid unico = idempotencia
CREATE TABLE asistencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid VARCHAR(64) NOT NULL,
    id_evento BIGINT NOT NULL REFERENCES evento (id),
    id_participante VARCHAR(40) NOT NULL REFERENCES participante (id),
    tipo_participante VARCHAR(20) NOT NULL,
    marcado_en BIGINT NOT NULL,
    latitud DOUBLE PRECISION,
    longitud DOUBLE PRECISION,
    distancia_metros DOUBLE PRECISION,
    estado_validacion VARCHAR(20) NOT NULL,
    inscrito_en_sitio BOOLEAN NOT NULL,
    registrado_por BIGINT,
    dispositivo_id VARCHAR(100),
    recibido_en BIGINT NOT NULL,
    CONSTRAINT uk_asistencia_uuid UNIQUE (uuid),
    CONSTRAINT uk_asistencia_evento_participante UNIQUE (id_evento, id_participante)
);

-- Encuestas; participante_id sin clave foranea porque puede ser anonima o llegar antes que la marca
CREATE TABLE encuesta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid VARCHAR(64) NOT NULL,
    id_evento BIGINT NOT NULL REFERENCES evento (id),
    participante_id VARCHAR(40),
    satisfaccion INTEGER NOT NULL CHECK (satisfaccion BETWEEN 1 AND 5),
    utilidad INTEGER NOT NULL CHECK (utilidad BETWEEN 1 AND 5),
    comentario VARCHAR(500),
    fecha_envio BIGINT NOT NULL,
    recibido_en BIGINT NOT NULL,
    CONSTRAINT uk_encuesta_uuid UNIQUE (uuid)
);
CREATE INDEX ix_encuesta_evento_participante ON encuesta (id_evento, participante_id);
