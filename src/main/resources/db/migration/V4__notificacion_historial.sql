-- Historial de notificaciones enviadas (manuales y recordatorios)
CREATE TABLE notificacion_historial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(120) NOT NULL,
    cuerpo VARCHAR(500) NOT NULL,
    roles VARCHAR(120),
    tipo VARCHAR(30) NOT NULL,
    evento_id BIGINT,
    enviado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dispositivos_enviados INT NOT NULL DEFAULT 0
);

CREATE INDEX ix_notificacion_historial_enviado_en ON notificacion_historial (enviado_en DESC);
CREATE INDEX ix_notificacion_historial_evento_tipo ON notificacion_historial (evento_id, tipo);
